/*
 * `en` is `as const`, so every value is a literal type ("Copy", not string).
 * Deriving the catalogue type straight from it would demand that every other
 * locale repeat the English wording verbatim. Widening the string leaves keeps
 * the key structure enforced — a missing or misspelled key is still an error —
 * while letting translations carry their own text.
 */
type WidenStrings<T> = {
  [K in keyof T]: T[K] extends string ? string : WidenStrings<T[K]>;
};

export type Messages = WidenStrings<typeof en>;
